-- NGL MB Confessions database for Neon (PostgreSQL)
-- Run in: Neon Console -> SQL Editor -> paste -> Run.

CREATE EXTENSION IF NOT EXISTS citext;

CREATE TABLE IF NOT EXISTS admins (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email CITEXT NOT NULL UNIQUE,
  name VARCHAR(60) NOT NULL,
  ngl_link VARCHAR(500) NULL,
  password_hash VARCHAR(255) NOT NULL,
  created_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS members (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email CITEXT NOT NULL UNIQUE,
  name VARCHAR(60) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  created_at BIGINT NOT NULL
);

-- Photos are stored in the database because Vercel has no permanent file storage.
CREATE TABLE IF NOT EXISTS photos (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  mime VARCHAR(30) NOT NULL,
  data TEXT NOT NULL,
  created_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS posts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  body TEXT NOT NULL,
  photo VARCHAR(200) NULL,
  admin_id INTEGER NULL REFERENCES admins(id) ON DELETE SET NULL,
  created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_posts_admin ON posts (admin_id);

CREATE TABLE IF NOT EXISTS comments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  post_id INTEGER NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
  body TEXT NOT NULL,
  created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_comments_post ON comments (post_id, id);

CREATE TABLE IF NOT EXISTS reactions (
  post_id INTEGER NOT NULL REFERENCES posts(id) ON DELETE CASCADE,
  voter VARCHAR(64) NOT NULL,
  kind SMALLINT NOT NULL,
  PRIMARY KEY (post_id, voter)
);

CREATE TABLE IF NOT EXISTS settings (
  k VARCHAR(50) NOT NULL PRIMARY KEY,
  v VARCHAR(500) NOT NULL
);

CREATE TABLE IF NOT EXISTS login_attempts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ip VARCHAR(45) NOT NULL,
  created_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_ip ON login_attempts (ip);

